import { createOAuthHeader } from '../oauth'

it('matches the OAuth 1 signature generated by İşCep 10.12.0', () => {
  expect(createOAuthHeader(
    'https://mobil.isbank.com.tr/ClientGateway/IsCepLogin/PasswordVerification',
    '123456',
    '1700000000'
  )).toBe(
    'OAuth oauth_body_hash="2jmj7l5rSw0yVb/vlWAYkK/YBwk=",' +
    'oauth_consumer_key="A562432E-061C-4584-8252-19F153BF0E31",' +
    'oauth_nonce="123456",' +
    'oauth_timestamp="1700000000",' +
    'oauth_signature_method="HMAC-SHA1",' +
    'oauth_version="1.0",' +
    'oauth_signature="q50I9UY/FNa/3cv4HZVjYBBXD7g="'
  )
})
